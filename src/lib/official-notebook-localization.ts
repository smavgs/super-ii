export function localizeOfficialNotebookMarkdown(source: string, locale: 'en' | 'ru'): string {
  if (locale !== 'ru') return source;
  const heading = source.split('\n', 1)[0]?.trim();
  return russianMarkdownByHeading[heading] ?? source;
}
